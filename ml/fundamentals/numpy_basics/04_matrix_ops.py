import numpy as np

# ============================================================
# 第一步：向量的基本运算
# ============================================================
# 先搞清楚这几个概念：
#
#   标量 (scalar)  → 一个数       如 5
#   向量 (vector)  → 一列数       如 [1, 2, 3]         shape (3,)
#   矩阵 (matrix)  → 二维表格     如 [[1,2],[3,4]]     shape (2, 2)
#   张量 (tensor)  → 三维及以上   如 shape (2, 3, 4)   就是"多个矩阵叠在一起"
#
# 记住：shape 里每个数字代表那个维度的大小。
#   shape (3,)   = 一维，3 个元素
#   shape (2, 3) = 二维，2 行 3 列
#   shape (2,3,4)= 三维，2 层，每层 3 行 4 列

print("=" * 55)
print("第一步：向量与矩阵的基本概念")
print("=" * 55)

v = np.array([1, 2, 3])
print("向量 v:", v, " shape:", v.shape)     # (3,)

M = np.array([[1, 2, 3], [4, 5, 6]])
print("矩阵 M:\n", M, "\n shape:", M.shape)  # (2, 3)

T = np.ones((2, 3, 4))                      # 三维张量
print("张量 T shape:", T.shape)              # (2, 3, 4)

# ============================================================
# 第二步：逐元素运算（Element-wise）
# ============================================================
# 最基础的运算：两个形状相同的数组，对应位置做运算。
# 加、减、乘、除、幂都是逐元素的。
#
# ★ 重要：在 NumPy 中，a * b 是逐元素乘，不是矩阵乘！
#   矩阵乘要用 a @ b 或 np.dot(a, b)

print("\n" + "=" * 55)
print("第二步：逐元素运算（对应位置算）")
print("=" * 55)

a = np.array([1, 2, 3])
b = np.array([4, 5, 6])

print("a =", a)
print("b =", b)
print("a + b =", a + b)
print("a - b =", a - b)
print("a * b =", a * b)       # ← 逐元素乘！
print("a / b =", a / b)
print("a ** 2 =", a ** 2)

# 二维数组的逐元素运算
A = np.array([[1, 2], [3, 4]])
B = np.array([[5, 6], [7, 8]])

print("\nA:\n", A)
print("B:\n", B)
print("A * B（逐元素乘）:\n", A * B)
# 注意：这不是线性代数的矩阵乘法！
# 它只是把两个矩阵对应位置拿过来相乘。

# ★ 记下来，新手最容易错的地方：
#   a * b  → 逐元素乘法（对应位置相乘）
#   a @ b  → 矩阵乘法（线性代数中的乘法）


# ============================================================
# 第三步：矩阵乘法 @ / np.dot / np.matmul
# ============================================================
# 这是机器学习中最常用的运算。
#
# 维度匹配规则：
#   两个矩阵 A × B，A 的列数必须等于 B 的行数。
#   A shape (m, n) × B shape (n, p) → 结果 shape (m, p)
#
# 记忆口诀："内维匹配，外维即结果"
#   (m, n) @ (n, p) → (m, p)
#    ↑___↑            ↑___↑
#   内维相等          外维组成结果

print("\n" + "=" * 55)
print("第三步：矩阵乘法 @（机器学习核心操作）")
print("=" * 55)

A = np.array([[1, 2], [3, 4]])   # shape (2, 2)
B = np.array([[5, 6], [7, 8]])   # shape (2, 2)

print("A: shape", A.shape)
print(A)
print("B: shape", B.shape)
print(B)

print("\nA @ B（矩阵乘）:\n", A @ B)

# 矩阵乘法的计算过程：
# 结果的 [i, j] = A 的第 i 行 × B 的第 j 列（对应乘再加）
# ┌─────┐   ┌─────┐   ┌─────────────────────┐
# │ 1 2 │   │ 5 6 │   │ 1×5+2×7  1×6+2×8   │
# │ 3 4 │ × │ 7 8 │ = │ 3×5+4×7  3×6+4×8   │
# └─────┘   └─────┘   └─────────────────────┘
#                       [0,0]       [0,1]
#                       [1,0]       [1,1]

# --- 矩阵 × 向量 ---
mat = np.array([[1, 2, 3], [4, 5, 6]])   # shape (2, 3)
vec = np.array([1, 2, 3])                 # shape (3,)
print("\n矩阵 × 向量:")
print("mat:", mat.shape)
print("vec:", vec.shape)
print("mat @ vec:", mat @ vec)            # shape (2,)
# 结果 [i] = mat 的第 i 行 × vec（对应相乘再加）
# [1×1+2×2+3×3, 4×1+5×2+6×3] = [14, 32]

# --- 维度不匹配会报错 ---
try:
    wrong = np.array([[1, 2], [3, 4]]) @ np.array([1, 2, 3])
except ValueError as e:
    print("\n维度不匹配示例:")
    print("  (2,2) @ (3,) →", e)

# --- 验证：逐元素乘 vs 矩阵乘完全不同 ---
print("\n★ 对比 A * B 和 A @ B 完全不同")
print("A * B（逐元素乘）:\n", A * B)
print("A @ B（矩阵乘）:\n", A @ B)


# ============================================================
# 第四步：转置 .T
# ============================================================
# 转置就是"行列互换"——把 (m, n) 变成 (n, m)。
# 什么时候用？矩阵乘法维度不匹配时，转置一下就能乘了。

print("\n" + "=" * 55)
print("第四步：转置 .T（行列互换）")
print("=" * 55)

A = np.array([[1, 2, 3], [4, 5, 6]])   # shape (2, 3)
print("A:\n", A, "\nshape:", A.shape)
print("A.T:\n", A.T, "\nshape:", A.T.shape)

# 应用场景：计算 x^T x（向量内积）
x = np.array([1, 2, 3])
print("\n向量 x:", x)
print("x @ x（内积）:", x @ x)       # 1×1+2×2+3×3=14


# ============================================================
# 第五步：逆矩阵与解线性方程组
# ============================================================
# 逆矩阵 A^-1：满足 A × A^-1 = 单位矩阵 I 的矩阵。
# 类比实数中 5 × (1/5) = 1。
#
# 解方程组 Ax = b，两边乘 A^-1 得 x = A^-1 b。
# 但代码里不要自己算逆来解方程！
# 用 np.linalg.solve(A, b) 更快更稳定。

print("\n" + "=" * 55)
print("第五步：逆矩阵与解方程组")
print("=" * 55)

A = np.array([[3, 1], [1, 2]])
print("A:\n", A)

# 逆矩阵
A_inv = np.linalg.inv(A)
print("\nA^-1:\n", A_inv.round(3))

# 验证：A × A^-1 = I（单位矩阵）
identity = A @ A_inv
print("A @ A^-1:\n", identity.round(3))
# 对角线接近 1，非对角线接近 0 就是对的

# --- 解方程组 ---
# 方程组：
#   3x +  y = 9
#    x + 2y = 8
# 写成矩阵形式：A × [x, y] = [9, 8]
b = np.array([9, 8])
x = np.linalg.solve(A, b)
print("\n解方程组 Ax = b")
print("x =", x, "（即 x=2, y=3）")
print("验证 A @ x:", A @ x, "（应是 [9, 8]）")


# ============================================================
# 第六步：特征值与特征向量
# ============================================================
# 这是新手最容易卡住的地方。从几何角度理解：
#
#   对向量 v 做矩阵变换 A：
#     普通向量：方向会变
#     特征向量：方向不变，只缩放 λ 倍
#
#   即：A × v = λ × v
#       ↑变换  ↑方向不变  ↑缩放倍数（特征值）
#
#   最大的特征值对应变换最重要的方向 → PCA 的核心思想

print("\n" + "=" * 55)
print("第六步：特征值与特征向量（几何直观）")
print("=" * 55)

A = np.array([[4, -2], [1, 1]])
print("矩阵 A:\n", A)

eigvals, eigvecs = np.linalg.eig(A)
print("\n特征值:", eigvals)
print("特征向量（列向量）:\n", eigvecs)
# eigvecs[:, i] 是第 i 个特征向量
# eigvals[i] 是第 i 个特征值

# 验证 A × v = λ × v
print("\n验证 A × v = λ × v（方向不变）:")
for i in range(len(eigvals)):
    v = eigvecs[:, i]
    lam = eigvals[i]
    print(f"  v{i}: A·v = {A @ v}")
    print(f"       λ·v = {lam * v}")
    print(f"       基本相等 OK（有小误差正常）")


# ============================================================
# 第七步：范数（衡量向量/矩阵的长度）
# ============================================================
# L2 范数：√(x1^2 + x2^2 + ... + xn^2)  —— 欧几里得距离
# L1 范数：|x1| + |x2| + ... + |xn|      —— 绝对值之和

print("\n" + "=" * 55)
print("第七步：范数（衡量向量长度）")
print("=" * 55)

v = np.array([3, 4])
